public readonly struct BucketVisualLayout
{
    public readonly float TopY;
    public readonly float BottomY;
    public readonly float OutletEndY;

    public BucketVisualLayout(float topY, float bottomY, float outletEndY)
    {
        TopY = topY;
        BottomY = bottomY;
        OutletEndY = outletEndY;
    }
}